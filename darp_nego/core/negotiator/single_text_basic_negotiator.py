    def reveal_client(self) -> List[BasicDARPClient]:
        """
        Reveal a client that this agent is willing to negotiate over.
        Returns the client with the highest associated cost.
        """
        my_costs = [self.get_associated_cost([c.client_id]) for c in self.darp_problem.clients.values()]
        avg_cost = np.mean(my_costs)
        std_cost = np.std(my_costs)
        cv = std_cost / avg_cost  # Coefficient of variation
        
        # If costs are very variable (high CV), be more conservative
        # If costs are similar (low CV), can share more
        if cv > 0.5:  # High variability
            threshold = avg_cost + (0.8 * std_cost)  # More conservative
        elif cv > 0.3:  # Medium variability
            threshold = avg_cost + (1.0 * std_cost)  # Standard
        else:  # Low variability
            threshold = avg_cost + (1.2 * std_cost)  # More generous
        
        outliers = [c for c in self.darp_problem.clients.values() 
                   if self.get_associated_cost([c.client_id]) > threshold]
        
        if not outliers:
            return [max(self.darp_problem.clients.values(), 
                       key=lambda c: self.get_associated_cost([c.client_id]))]
        
        return outliers[:max(1, len(self.darp_problem.clients) // 2)]

