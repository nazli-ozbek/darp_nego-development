    def is_acceptable(self, outcome: BasicDARPOutcome, **kwargs) -> Tuple[bool, float]:
        """
        Determine if a proposed outcome is acceptable to this agent.
        Returns:
            - A boolean indicating if the utility change meets or exceeds the threshold.
            - The calculated utility change value.
        """
        # TODO: improve threshold calculation (maybe dynamic) or use a different approach
        giving = []
        getting = []        
        for client_id, owner_id in outcome.items():
            current_owner = self._client_owners.get(client_id)
            if current_owner == self.agent_id and owner_id != self.agent_id:
                giving.append(client_id)
            elif current_owner != self.agent_id and owner_id == self.agent_id:
                getting.append(client_id)
        temp_utility = self.get_utility(including=getting, excluding=giving)
        # Persist delta so update_agreement() can commit the accepted proposal.
        self.utility_change = temp_utility - self.current_utility
        is_accepted = temp_utility <= self.current_utility
        
        # Concise decision summary
        exchange_summary = ""
        if giving and getting:
            exchange_summary = f" (give {giving}, get {getting})"
        elif giving:
            exchange_summary = f" (give {giving})"
        elif getting:
            exchange_summary = f" (get {getting})"
        
        if is_accepted:
            emoji, decision = "✅", "ACCEPT"
        else:
            emoji, decision = "❌", "REJECT"
        print(f"{emoji} Agent {self.agent_id}: {decision} - new utility {temp_utility:.0f}{exchange_summary}")
        
        return is_accepted, temp_utility
